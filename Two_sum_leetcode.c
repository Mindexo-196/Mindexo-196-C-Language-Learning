/* ============================================================================
 * LeetCode 1. Two Sum（两数之和）—— 暴力枚举解法
 *
 * 题目：给定整数数组 nums 和目标值 target，找出和为目标值的两个整数，返回下标。
 *       保证每种输入只有一个答案，且不能使用两次相同元素。
 *
 * 输入格式（按 LeetCode 展示形式解析）：
 *       nums = [2,7,11,15], target = 9     →  输出 [0,1]
 *       nums = [3,2,4],     target = 6     →  输出 [1,2]
 *
 * 复杂度：时间 O(n^2)，空间 O(1)。
 * ==========================================================================*/

#include <stdio.h>   /* scanf / printf / getchar / EOF / fprintf / stderr */
#include <ctype.h>   /* isspace() */

/* 数组容量上限。
 * 用宏而非 const int：C 语言中数组长度要求编译期常量表达式。
 * 注意题目要求 n 可达 10^4，这里只有 1000 —— 见文末「不足」第 1 条。 */
#define MAXN 1000

/* ----------------------------------------------------------------------------
 * finder —— 找出和等于 target 的两个下标（双重循环暴力枚举）
 *
 * num    ：数组。形参实际退化为指针，const 表示函数内不修改它。
 * length ：元素个数。★ 必须由调用方传入 —— 函数内 sizeof(num) 得到的是
 *          指针大小（8 字节），sizeof(num)/sizeof(num[0]) 恒为 2，与真实长度无关。
 * target ：目标和。
 *
 * 内层 j 从 i+1 开始：既避免自己和自己相加，也避免 (i,j) 与 (j,i) 重复检查。
 * -------------------------------------------------------------------------- */
void finder(const int num[], int length, int target)
{
    int i, j;
    int found = 0;   /* 是否找到答案的标记，0 为假、非 0 为真 */

    for (i = 0; i < length; i++)
    {
        for (j = i + 1; j < length; j++)
        {
            if (num[i] + num[j] == target)
            {
                printf("[%d,%d]\n", i, j);   /* %d 输出的是下标，不是元素值 */
                found = 1;
            }
        }
    }

    /* 没有这段的话，无解时程序什么都不输出，调用方无法区分「无解」和「崩溃」 */
    if (found == 0)
    {
        printf("no answer\n");
    }
}

/* ----------------------------------------------------------------------------
 * skip_until —— 不断读取并丢弃字符，直到遇到 ch 或文件结束
 *
 * 返回：读到的目标字符；若提前遇到 EOF 则返回 EOF。
 * static 表示内部链接：只在本文件可见，不对外暴露。
 *
 * 注意副作用：目标字符本身也会被消费掉。
 * 另外参数和局部变量都必须用 int —— getchar() 返回 int 以便同时表示
 * 256 个字符值和 EOF(-1)；若用 char，字节 0xFF 会被截断成 -1 而误判为 EOF。
 * -------------------------------------------------------------------------- */
static int skip_until(int ch)
{
    int c;

    /* 外层括号不可省：!= 优先级高于 =，否则会解析成 c = (getchar() != EOF)，
     * c 只能得到 0 或 1。&& 短路保证先判 EOF 再判目标字符。
     * 循环体为空语句，工作全在条件表达式里完成。 */
    while ((c = getchar()) != EOF && c != ch)
        ;

    return c;
}

/* ----------------------------------------------------------------------------
 * main —— 解析输入并调用 finder
 * -------------------------------------------------------------------------- */
int main(void)
{
    int nums[MAXN];   /* 1000 个 int 约占 4KB，放栈上安全 */
    int i = 0;        /* 既是数组下标，也是读完后数组的有效元素个数 */
    int target = 0;
    int c;

    /* ---------- 第一步：跳过 "nums = " 前缀，定位到 '[' ---------- */
    if (skip_until('[') == EOF)
    {
        /* 错误信息走 stderr，不污染 stdout 上的正常结果 */
        fprintf(stderr, "input error : no '[' \n");
        return 1;
    }

    /* ---------- 第二步：循环读取数组元素，直到 ']' ---------- */
    /* 用 scanf 的返回值作循环条件：只有成功读到一个整数时才返回 1。
     * 注意 %d 会跳过前导空白但不会跳过逗号，所以逗号要靠下面的 do-while 吃掉。 */
    while (scanf("%d", &nums[i]) == 1)
    {
        i++;

        /* 容量保护：越界写入是未定义行为，可能破坏栈上其他变量甚至崩溃 */
        if (i >= MAXN)
        {
            fprintf(stderr, "too many numbers (max %d)\n", MAXN);
            return 1;
        }

        /* 吃掉数字后面的空白字符 */
        do
        {
            c = getchar();
        } while (c != EOF && isspace(c));

        /* 此时 c 是第一个非空白字符，即紧接着的分隔符：
         * ']' 表示数组结束，',' 表示后面还有元素，EOF 表示输入意外结束。
         * 这几个字符都已被消费掉，流位置正好在下一个位置。 */
        if (c == ']' || c == EOF)
            break;
    }

    /* ---------- 第三步：跳过 "], target = " 中的 '='，再读 target ---------- */
    /* 检查返回值，避免把未初始化的 target 传进 finder（未定义行为） */
    if (skip_until('=') == EOF || scanf("%d", &target) != 1)
    {
        fprintf(stderr, "input error: no target\n");
        return 1;
    }

    /* ---------- 第四步（可选）：回显解析结果，调试用 ---------- */
    /* 注意：必须先结束 for 再单独打印 "], target = ..."，
     * 否则那句会随每个元素重复打印。 */
    // printf("nums = [");
    // for (k = 0; k < i; k++)
    //     printf("%d%s", nums[k], (k + 1 < i) ? "," : "");
    // printf("], target = %d\n", target);

    /* 把有效元素个数 i 作为 length 显式传入 —— 程序能正确工作的关键 */
    finder(nums, i, target);

    return 0;
}

/* ============================================================================
 * 不足与改进方向
 * 1. MAXN 只有 1000，题目要求 n 可达 10^4：应改为 10004 或 malloc 动态分配。
 * 2. O(n^2) 在 n=10^4 时约 5×10^7 次比较：可用哈希表降到 O(n)。
 * 3. finder 返回 void、直接打印，无法复用：可返回 int 或用出参带回下标。
 * 4. 溢加风险：两元素可达 ±10^9，相加可达 ±2×10^9，超出 int 正向范围
 *    （约 2.147×10^9）。稳妥写法：
 *        (long long)num[i] + num[j] == (long long)target
 * ==========================================================================*/
