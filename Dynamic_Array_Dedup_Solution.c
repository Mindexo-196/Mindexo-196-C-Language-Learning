// C 语言入门算法题：数组去重并统计频率
// 难度：★★☆☆☆　知识点：函数、数组、指针、循环、条件判断

// 题目描述
// 读入 n 个整数（可能有重复），要求按首次出现的顺序输出去重后的结果，并统计每个数出现了多少次。

// 也就是说：每遇到一个新的数就保留它，后面重复出现的数直接忽略；最后按"原来第一次出现的先后顺序"输出，不能排序。

// 输入格式
// 第一行一个整数 n（1 ≤ n ≤ 1000）。 第二行 n 个整数，每个整数的范围是 -1000 ≤ a[i] ≤ 1000。

// 输出格式
// 分两部分输出：

// 第一行：去重后的数，用空格分隔。
// 后面每行一个：数值 出现次数，顺序与第一行一致。
// 样例输入
// 代码块


// 8
// 3 1 4 1 5 9 3 1
// 样例输出
// 代码块


// 3 1 4 5 9
// 3 2
// 1 3
// 4 1
// 5 1
// 9 1

